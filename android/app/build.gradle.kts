import org.jetbrains.kotlin.gradle.dsl.JvmTarget

plugins {
    id("com.android.application")
    id("org.jetbrains.kotlin.android")
    id("org.jetbrains.kotlin.plugin.compose")
}

// One version for both apps: read it from the desktop CMake project.
val kvantVersion: String = Regex("""project\(kvant VERSION ([0-9.]+)""")
    .find(rootDir.resolve("../CMakeLists.txt").readText())!!.groupValues[1]
val versionParts = kvantVersion.split(".").map { it.toInt() }

// Release signing comes from the environment (GitHub Actions secrets), never from the repo.
val keystorePath: String? = System.getenv("KVANT_KEYSTORE")

android {
    namespace = "io.github.proshiv85_byte.kvant"
    compileSdk = 36

    defaultConfig {
        applicationId = "io.github.proshiv85_byte.kvant"
        minSdk = 26
        targetSdk = 36
        versionCode = versionParts[0] * 10000 + versionParts[1] * 100 + versionParts[2]
        versionName = kvantVersion
    }

    signingConfigs {
        if (keystorePath != null) {
            create("release") {
                storeFile = file(keystorePath)
                storePassword = System.getenv("KVANT_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("KVANT_KEY_ALIAS")
                keyPassword = System.getenv("KVANT_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            if (keystorePath != null) signingConfig = signingConfigs.getByName("release")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
    }
}

kotlin {
    compilerOptions {
        jvmTarget.set(JvmTarget.JVM_17)
    }
}

